def translate(value: Any, language: str | None = None) -> Any:
    if not isinstance(value, str):
        return value
    language = language or st.session_state.get("ui_language", "id")
    if language != "id":
        return value
    for source in sorted(ID_TRANSLATIONS, key=len, reverse=True):
        value = value.replace(source, ID_TRANSLATIONS[source])
    return value


def install_streamlit_translation() -> None:
    """Translate display strings while preserving English values used in code."""
    from streamlit.delta_generator import DeltaGenerator

    display_methods = {
        "markdown", "caption", "info", "warning", "error", "success", "title",
        "header", "subheader", "text", "write", "button", "text_input", "text_area",
        "checkbox", "selectbox", "multiselect", "radio", "number_input", "date_input",
        "file_uploader", "download_button", "link_button", "form_submit_button", "dataframe",
    }
    for name in display_methods:
        original = getattr(DeltaGenerator, name, None)
        if original is None:
            continue
        if not getattr(original, "_govapp_i18n_wrapped", False):
            def make_wrapper(method_name: str, method: Any):
                def translated_method(self, *args, **kwargs):
                    args = list(args)
                    if args and isinstance(args[0], str):
                        args[0] = translate(args[0])
                    for key in ("label", "help", "placeholder", "caption", "label_visibility"):
                        if isinstance(kwargs.get(key), str):
                            kwargs[key] = translate(kwargs[key])
                    if method_name in {"radio", "selectbox", "multiselect"} and kwargs.get("format_func") is not None:
                        formatter = kwargs["format_func"]
                        kwargs["format_func"] = lambda item: translate(formatter(item))
                    if method_name == "dataframe" and args and isinstance(args[0], pd.DataFrame):
                        frame = args[0].copy()
                        for column in frame.select_dtypes(include=["object", "string"]).columns:
                            if str(column).lower() in {"label", "sentiment", "class"}:
                                frame[column] = frame[column].map(lambda item: translate(item))
                        renames = {column: translate(str(column)) for column in frame.columns}
                        frame.rename(columns=renames, inplace=True)
                        config = kwargs.get("column_config")
                        if isinstance(config, dict):
                            translated_config = {}
                            for column, spec in config.items():
                                translated_spec = dict(spec) if isinstance(spec, dict) else spec
                                if isinstance(translated_spec, dict) and isinstance(translated_spec.get("label"), str):
                                    translated_spec["label"] = translate(translated_spec["label"])
                                translated_config[renames.get(column, column)] = translated_spec
                            kwargs["column_config"] = translated_config
                        if st.session_state.get("ui_theme", "dark") == "light":
                            table_body, table_stripe, table_header = "#ffffff", "#f5f7fb", "#eaf0f8"
                            table_text, table_border = "#1c2940", "#d5deeb"
                        else:
                            table_body, table_stripe, table_header = "#141a26", "#1a2230", "#202b3c"
                            table_text, table_border = "#f5f8ff", "#334155"
                        args[0] = frame.style.set_properties(
                            **{
                                "background-color": table_body,
                                "color": table_text,
                                "border-color": table_border,
                            }
                        ).set_table_styles(
                            [
                                {"selector": "thead th", "props": [
                                    ("background-color", table_header),
                                    ("color", table_text),
                                    ("border-color", table_border),
                                ]},
                                {"selector": "tbody tr:nth-child(even) td", "props": [
                                    ("background-color", table_stripe),
                                ]},
                                {"selector": "table", "props": [
                                    ("border-color", table_border),
                                ]},
                            ],
                            overwrite=False,
                        )
                    return method(self, *args, **kwargs)

                translated_method._govapp_i18n_wrapped = True
                return translated_method

            translated_method = make_wrapper(name, original)
            setattr(DeltaGenerator, name, translated_method)
        else:
            translated_method = original

        # Streamlit's top-level shortcuts (st.markdown, st.info, etc.) are
        # bound before DeltaGenerator is patched, so wrap those aliases too.
        shortcut = getattr(st, name, None)
        if callable(shortcut) and not getattr(shortcut, "_govapp_i18n_wrapped", False):
            generator = getattr(shortcut, "__self__", None)
            if generator is not None:
                def make_shortcut(method: Any, bound_generator: Any):
                    def translated_shortcut(*args, **kwargs):
                        return method(bound_generator, *args, **kwargs)

                    translated_shortcut._govapp_i18n_wrapped = True
                    return translated_shortcut

                setattr(st, name, make_shortcut(translated_method, generator))
    DeltaGenerator._govapp_i18n_installed = True
